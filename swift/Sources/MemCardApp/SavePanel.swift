import Foundation

extension URL {
    /// Путь с расширением: если пользователь стёр его в поле имени,
    /// подставляет запасное.
    ///
    /// В окне сохранения macOS имя предлагается вместе с расширением, и
    /// набирая своё, его затирают заодно - файл уходил на диск голым.
    /// Ни игра, ни эмулятор такой не подхватят: они узнают сейв по
    /// расширению.
    func named(_ fallback: String) -> URL {
        pathExtension.isEmpty ? appendingPathExtension(fallback) : self
    }
}
